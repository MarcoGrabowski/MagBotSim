import numpy as np


class StationCollisionProxies:
    """Hidden collision proxies that mimic the mechanics of the station switch, i.e. the interface between the rail mounts of a
    MagBot, the mover adapters, and the station pins.

    The rail mount, mover adapter and station meshes are visual-only, since MuJoCo collides meshes by their convex hulls, which would
    overlap the docked MagBot and the movers. Instead, the following proxies (boxes) collide with everything:

    - rail rod (one per mover): the dovetail of the mover adapter (``m_i_rail``) that slides between the jaws of a rail mount.
    - rail mount proxy (one per rail mount): a disk-shaped body with the footprint of the real rail mount (a disk, which is cut flat
      on one side and has two shoulders there). Its lower layer consists of the two jaws, which form a channel along the x-axis of
      the rail mount (= x-axis of the mover), through which the rail rod slides when an empty mover enters or leaves a station. Its
      upper layer contains two holes along the y-axis of the rail mount (= x-axis of the station), through which the station pins
      slide when the MagBot is taken out of or moved back into the station. The proxy consists of convex mesh pieces (MuJoCo collides
      meshes by their convex hulls), whose mesh assets are generated by ``assets_xml_str()``.
    - station pins (two per connection): the pins of the station that hold a parked rail mount.

    All dimensions are given in the rail mount body frame, relative to the rail mount origin (= origin of the mover adapter when the
    rail mount is welded to the mover).

    The rail rods and station pins are boxes. All proxies are inflated by ``INFLATION`` (on all sides) to avoid z-fighting with the
    visual meshes, whose surfaces they would otherwise share. The slots are widened accordingly,
    i.e. the sideways clearance is exactly ``tol``.

    :param tol: the sideways misalignment [m] with which a mover (or a MagBot carried by movers) can enter a station without
        colliding. With ``tol=0``, the proxies match the real geometries exactly, i.e. in practice they always collide.
        Defaults to 0.002
    """

    PROXY_NAME_PREFIX = 'proxy_'        # prefix of all proxy geom names
    GEOM_GROUP = 3                      # hidden by default in the MuJoCo viewer

    # rail mount (rail mount body frame)
    # footprint (rail_mount_m0.stl, rail_mount_m1m2.stl; mirrored in x-direction for connection 2): a disk, which is cut flat at
    # x=RAIL_MOUNT_X_MIN. For |y| <= JAW_OUTER_Y, the rail mount has shoulders, which reach up to the flat side.
    RAIL_MOUNT_RADIUS = 0.07            # [m]
    RAIL_MOUNT_X_MIN = -0.065           # [m]
    RAIL_MOUNT_TOP_Z = 0.0285           # [m] top of the proxy (the rotation plate starts at this height)
    JAW_OUTER_Y = 0.05                  # [m] outer edge of the jaws (|y|) = half width of the shoulders
    CIRCLE_SEGMENTS = 12                # number of polygon segments of the (full) disk
    # rail rod: dovetail of the mover adapter, sized to the gap between the jaws at their narrowest point (bottom)
    # y-range in the mover adapter body frame (along the x-axis of the rail mount = x-axis of the mover): from the end flange of the
    # mover adapter to the end of its straight part (the chamfered nose of the mover adapter, which reaches y=0.07 only at its
    # center line, is omitted)
    RAIL_ROD_Y_RANGE = (-0.07, 0.05)    # [m]
    RAIL_ROD_HALF_W = 0.025             # [m] half width
    RAIL_ROD_Z_RANGE = (0.0005, 0.02)   # [m] (the bottom is slightly above the top of the mover, which is at z=0.0001)
    # station pins (station_m0m1.stl / station_m2.stl), centered in the holes of the rail mount (rail_mount_m0.stl /
    # rail_mount_m1m2.stl: 12.55 x 4.35 mm, i.e. the real pins have a clearance of about 0.3 mm sideways and 0.2 mm vertically)
    HOLE_X = 0.0325                     # [m] x-pos of the hole centers (+/-)
    PIN_W = 0.0119                      # [m] width of the station pins
    PIN_H = 0.00395                     # [m] height of the station pins
    PIN_CENTER_Z = 0.024175             # [m] z-pos of the hole centers (= z-pos of the pin centers)
    PIN_TIP = 0.064                     # [m] distance of the pin tips from the rail mount center (along the x-axis of the station)
    # vertical clearances (independent of tol)
    BOTTOM_CLEARANCE = 0.001            # [m] between the top of the mover (at z=0.0001) and the bottom of the rail mount proxy
    VERTICAL_CLEARANCE = 0.0005         # [m] between the top of the rail rod and the upper layer of the rail mount proxy
    # all proxies are inflated by this amount to avoid z-fighting with the visual meshes (the slots are widened accordingly)
    INFLATION = 0.0001                  # [m]

    def __init__(self, tol: float = 0.002) -> None:
        assert 0.0 <= tol < self.JAW_OUTER_Y - self.RAIL_ROD_HALF_W, 'tol is too large, the jaws would vanish'
        assert self.HOLE_X - 0.5 * self.PIN_W - tol > 0.0, 'tol is too large, the holes would overlap'
        self.tol = tol

    def _box_xml_str(self, name: str, lo: np.ndarray, hi: np.ndarray, rgba: str, indent: str) -> str:
        """Generate the XML string of an axis-aligned box proxy geom. The box is inflated by ``INFLATION`` on all sides.

        :param name: the name of the geom (without prefix)
        :param lo: the lower corner of the box (numpy array of shape (3,)) [m]
        :param hi: the upper corner of the box (numpy array of shape (3,)) [m]
        :param rgba: the color of the box
        :param indent: the indentation of the XML line
        :return: the XML string of the geom
        """
        pos, size = 0.5 * (lo + hi), 0.5 * (hi - lo) + self.INFLATION
        assert (size > self.INFLATION).all(), f'invalid proxy box {name}'
        return (
            f'{indent}<geom name="{self.PROXY_NAME_PREFIX}{name}" type="box" pos="{pos[0]:.6f} {pos[1]:.6f} {pos[2]:.6f}" '
            f'size="{size[0]:.6f} {size[1]:.6f} {size[2]:.6f}" density="0" group="{self.GEOM_GROUP}" rgba="{rgba}"/>'
        )

    def _footprint_points(self, x_range: tuple[float, float], y_range: tuple[float, float]) -> list[np.ndarray]:
        """Return the convex parts of the (inflated) rail mount footprint within a rectangle. The footprint is the union of the
        shoulders (a rectangle) and the disk on the right of the shoulders, which are both convex.

        :param x_range: the x-range (min, max) of the rectangle [m]
        :param y_range: the y-range (min, max) of the rectangle [m]
        :return: the 2D points of each convex part (numpy arrays of shape (num_points, 2)); the convex hull of the points is the part
        """
        r = self.RAIL_MOUNT_RADIUS + self.INFLATION
        y_shoulder = self.JAW_OUTER_Y + self.INFLATION
        x_shoulder = -np.sqrt(r**2 - y_shoulder**2)  # the shoulders end where the disk reaches |y| = y_shoulder
        parts = []
        # shoulders: rectangle [x_min, x_shoulder] x [-y_shoulder, y_shoulder]
        x0, x1 = max(x_range[0], self.RAIL_MOUNT_X_MIN - self.INFLATION), min(x_range[1], x_shoulder)
        y0, y1 = max(y_range[0], -y_shoulder), min(y_range[1], y_shoulder)
        if x1 - x0 > 1e-6 and y1 - y0 > 1e-6:
            parts.append(np.array([[x0, y0], [x1, y0], [x1, y1], [x0, y1]]))
        # disk (x >= x_shoulder): circle points, corners and intersections of the rectangle edges with the circle
        x0, x1 = max(x_range[0], x_shoulder), min(x_range[1], r)
        y0, y1 = max(y_range[0], -r), min(y_range[1], r)
        if x1 - x0 > 1e-6 and y1 - y0 > 1e-6:
            angles = np.linspace(0.0, 2 * np.pi, self.CIRCLE_SEGMENTS, endpoint=False)
            pts = [p for p in r * np.stack([np.cos(angles), np.sin(angles)], axis=1)]
            pts += [np.array([x, y]) for x in (x0, x1) for y in (y0, y1)]
            for x in (x0, x1):
                if abs(x) < r:
                    pts += [np.array([x, sign * np.sqrt(r**2 - x**2)]) for sign in (-1, 1)]
            for y in (y0, y1):
                if abs(y) < r:
                    pts += [np.array([sign * np.sqrt(r**2 - y**2), y]) for sign in (-1, 1)]
            pts = np.array(
                [p for p in pts if x0 - 1e-9 <= p[0] <= x1 + 1e-9 and y0 - 1e-9 <= p[1] <= y1 + 1e-9 and np.hypot(*p) <= r + 1e-9]
            )
            if len(pts) >= 3 and np.ptp(pts[:, 0]) > 1e-6 and np.ptp(pts[:, 1]) > 1e-6:
                parts.append(pts)
        return parts

    def _rail_mount_pieces(self, mirror_x: bool) -> list[tuple[str, np.ndarray]]:
        """Return the convex mesh pieces of the rail mount proxy (inflated by ``INFLATION``, slots widened accordingly).

        :param mirror_x: whether the footprint of the rail mount is mirrored in x-direction
        :return: a list of (piece name, 3D vertices (numpy array of shape (num_vertices, 3))) [m]
        """
        inf, y_jaw = np.inf, self.JAW_OUTER_Y + self.INFLATION
        z_bottom, z_top = self.BOTTOM_CLEARANCE, self.RAIL_MOUNT_TOP_Z
        z_layer = self.RAIL_ROD_Z_RANGE[1] + self.VERTICAL_CLEARANCE  # boundary between the lower and the upper layer
        # half widths of the channel for the rail rod and the holes for the station pins (the inflation of both proxies is
        # compensated, i.e. the sideways clearance is exactly tol)
        y_channel = self.RAIL_ROD_HALF_W + self.tol + 2 * self.INFLATION
        x_hole = 0.5 * self.PIN_W + self.tol + 2 * self.INFLATION
        regions = [
            # lower layer: jaws, which form the channel for the rail rod
            ('lower_0', (-inf, inf), (-y_jaw, -y_channel + self.INFLATION), (z_bottom, z_layer)),
            ('lower_1', (-inf, inf), (y_channel - self.INFLATION, y_jaw), (z_bottom, z_layer)),
            # upper layer: separated by the two holes for the station pins
            ('upper_0', (-inf, -self.HOLE_X - x_hole + self.INFLATION), (-inf, inf), (z_layer, z_top)),
            ('upper_1', (-self.HOLE_X + x_hole - self.INFLATION, self.HOLE_X - x_hole + self.INFLATION), (-inf, inf), (z_layer, z_top)),
            ('upper_2', (self.HOLE_X + x_hole - self.INFLATION, inf), (-inf, inf), (z_layer, z_top)),
        ]
        pieces = []
        for name, x_range, y_range, (z0, z1) in regions:
            if mirror_x:
                x_range = (-x_range[1], -x_range[0])
            for idx_part, pts in enumerate(self._footprint_points(x_range=x_range, y_range=y_range)):
                pts = pts * np.array([-1.0, 1.0]) if mirror_x else pts  # the footprint is defined for the unmirrored rail mount
                vertices = np.concatenate(
                    [np.column_stack([pts, np.full(len(pts), z)]) for z in (z0 - self.INFLATION, z1 + self.INFLATION)]
                )
                pieces.append((f'{name}_{idx_part}', vertices))
        return pieces

    @staticmethod
    def _mesh_name(mirror_x: bool, piece_name: str) -> str:
        return f'proxy_rail_mount{"_mirrored" if mirror_x else ""}_{piece_name}_mesh'

    def assets_xml_str(self) -> str:
        """Generate the XML string of the mesh assets of the rail mount proxies (required once per model if rail mount proxies are
        used).

        :return: the XML string of the mesh assets
        """
        lines = ['\n\t\t<!-- station collision proxies: rail mount proxy assets -->']
        for mirror_x in (False, True):
            for piece_name, vertices in self._rail_mount_pieces(mirror_x=mirror_x):
                vertex_str = ' '.join(f'{v:.7f}' for v in vertices.flatten())
                lines.append(f'\t\t<mesh name="{self._mesh_name(mirror_x, piece_name)}" vertex="{vertex_str}"/>')
        return '\n'.join(lines)

    def rail_mount_proxy_xml_str(self, body_name: str, mirror_x: bool = False, indent: str = '\t\t\t\t') -> str:
        """Generate the XML string of the rail mount proxy, which has to be added as a child body of the rail mount body. The mesh
        assets are generated by ``assets_xml_str()``.

        :param body_name: the name of the proxy body (also used as part of the geom names)
        :param mirror_x: whether the footprint of the rail mount is mirrored in x-direction (e.g. connection 2 of the Gripper MagBot),
            defaults to False
        :param indent: the indentation of the body XML line, defaults to 4 tabs
        :return: the XML string of the proxy body
        """
        lines = [f'{indent}<body name="{body_name}" pos="0 0 0">']
        for piece_name, _ in self._rail_mount_pieces(mirror_x=mirror_x):
            lines.append(
                f'{indent}\t<geom name="{self.PROXY_NAME_PREFIX}{body_name}_{piece_name}" type="mesh" '
                f'mesh="{self._mesh_name(mirror_x, piece_name)}" density="0" group="{self.GEOM_GROUP}" rgba="1 0.5 0 0.5"/>'
            )
        lines.append(f'{indent}</body>')
        return '\n'.join(lines)

    def rail_rod_xml_str(self, body_name: str, indent: str = '\t\t\t\t') -> str:
        """Generate the XML string of the rail rod, which has to be added as a child body of the mover adapter body (``m_i_rail``).
        The origin of the mover adapter body coincides with the rail mount origin if the rail mount is welded to the mover, and the
        y-axis of the mover adapter body is aligned with the x-axis of the rail mount (the mover adapter body is rotated by +/-90 deg
        relative to the mover).

        :param body_name: the name of the rail rod body (also used as part of the geom name)
        :param indent: the indentation of the body XML line, defaults to 4 tabs
        :return: the XML string of the rail rod body
        """
        lo = np.array([-self.RAIL_ROD_HALF_W, self.RAIL_ROD_Y_RANGE[0], self.RAIL_ROD_Z_RANGE[0]])
        hi = np.array([self.RAIL_ROD_HALF_W, self.RAIL_ROD_Y_RANGE[1], self.RAIL_ROD_Z_RANGE[1]])
        lines = [
            f'{indent}<body name="{body_name}" pos="0 0 0">',
            self._box_xml_str(body_name, lo, hi, '0 0.6 1 0.8', indent + '\t'),
            f'{indent}</body>',
        ]
        return '\n'.join(lines)

    def station_pins_xml_str(self, body_name: str, rail_mount_xy_pos: np.ndarray, rail_mount_z: float, indent: str = '\t\t\t') -> str:
        """Generate the XML string of the station pins, which has to be added as a child body of the station body. The x-axis of the
        station body frame is the axis along which the MagBot is taken out of the station, i.e. the pins are aligned with this axis
        and the x-axes of the parked rail mounts are aligned with the y-axis of the station body frame.

        :param body_name: the name of the pins body (also used as part of the geom names)
        :param rail_mount_xy_pos: the (x, y) positions of the parked rail mounts in the station body frame (numpy array of shape
            (num_connections, 2)) [m]
        :param rail_mount_z: the z-pos of the rail mount origin in the station body frame [m]
        :param indent: the indentation of the body XML line, defaults to 3 tabs
        :return: the XML string of the pins body
        """
        z_lo, z_hi = rail_mount_z + self.PIN_CENTER_Z - 0.5 * self.PIN_H, rail_mount_z + self.PIN_CENTER_Z + 0.5 * self.PIN_H
        lines = [f'{indent}<body name="{body_name}" pos="0 0 0">']
        for idx_c, (x_c, y_c) in enumerate(rail_mount_xy_pos):
            for idx_pin, y_hole in enumerate([-self.HOLE_X, self.HOLE_X]):
                # the pins reach from the station side of the rail mount footprint to their tips
                lo = np.array([x_c - self.RAIL_MOUNT_RADIUS, y_c + y_hole - 0.5 * self.PIN_W, z_lo])
                hi = np.array([x_c + self.PIN_TIP, y_c + y_hole + 0.5 * self.PIN_W, z_hi])
                lines.append(self._box_xml_str(f'{body_name}_c{idx_c}_{idx_pin}', lo, hi, '0.9 0 0.6 0.8', indent + '\t'))
        lines.append(f'{indent}</body>')
        return '\n'.join(lines)
